const assert = require('node:assert/strict');
const { mkdirSync, mkdtempSync } = require('node:fs');
const { resolve } = require('node:path');
const { launch, freePort } = require('./webview2-driver.cjs');
(async () => {
  mkdirSync('.data', { recursive: true }); mkdirSync('test-results', { recursive: true });
  const port = String(await freePort());
  const teacherData = resolve(mkdtempSync('.data/orb-teacher-'));
  const studentData = resolve(mkdtempSync('.data/orb-student-'));
  const environment = { SCHOOL_HEADLESS_TEST: '1', SCHOOL_TEST_PORT: port };
  const teacher = await launch({ env: { ...environment, SCHOOL_TEST_DATA: teacherData } });
  let student, restored;
  try {
    const teacherPage = await teacher.firstWindow();
    const host = await teacherPage.evaluate(() => window.desktop.host());
    assert.match(host.pairCode, /^[A-HJ-NP-Z2-9]{4}(-[A-HJ-NP-Z2-9]{4}){2}$/);
    await teacherPage.evaluate(() => window.desktop.request('/api/setup', 'POST', { school: 'مدرسة الشريقي', username: 'admin', password: 'Orb-test123', name: 'المعلم' }));
    await teacherPage.evaluate(() => window.desktop.request('/api/login', 'POST', { role: 'teacher', username: 'admin', password: 'Orb-test123' }));
    student = await launch({ env: { ...environment, SCHOOL_TEST_DATA: studentData } });
    const page = await student.firstWindow();
    const orb = page.locator('.connection-orb-button');
    await page.waitForFunction(() => document.querySelector('.connection-orb-button')?.classList.contains('is-red'));
    await page.screenshot({ path: 'test-results/orb-login-disconnected.png' });
    await orb.click();
    const dialog = page.getByRole('dialog');
    await dialog.getByRole('button', { name: /مدرسة الشريقي/ }).waitFor();
    assert.equal(await dialog.locator('textarea').count(), 0);
    assert.equal(await dialog.locator('input:visible').count(), 1);
    await page.screenshot({ path: 'test-results/orb-connection-panel.png' });
    await dialog.getByLabel('رمز الاتصال', { exact: true }).fill('AAAA-AAAA-AAAA');
    await dialog.getByRole('button', { name: 'الاتصال بجهاز المعلم', exact: true }).click();
    await dialog.getByRole('alert').waitFor();
    assert.match(await dialog.getByRole('alert').innerText(), /غير صحيح/);
    assert.equal((await page.evaluate(() => window.desktop.connectionState())).connected, false);
    await dialog.getByLabel('رمز الاتصال', { exact: true }).fill(host.pairCode.toLowerCase());
    await dialog.getByRole('button', { name: 'الاتصال بجهاز المعلم', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.connection-orb-button')?.classList.contains('is-green'));
    await dialog.getByRole('heading', { name: 'أهلًا بك في الصف' }).waitFor();
    await page.screenshot({ path: 'test-results/orb-connected-success.png' });
    await page.waitForFunction(() => document.querySelector('.connection-orb-button')?.classList.contains('is-blue'));
    await dialog.getByRole('button', { name: 'متابعة إلى تسجيل الدخول' }).click();
    assert.equal(await page.locator('.login-card form input').count(), 1);
    assert.equal(await page.evaluate(() => localStorage.getItem('school-scope')), host.fingerprint);
    const info = await page.evaluate(() => window.desktop.connectionState());
    assert.equal(info.connected, true); assert.equal(info.local, false);
    await page.screenshot({ path: 'test-results/orb-login-connected.png' });
    await page.setViewportSize({ width: 390, height: 844 });
    await orb.click();
    await page.waitForTimeout(250); // Allow the modal entrance animation to finish for visual QA.
    await page.screenshot({ path: 'test-results/orb-panel-mobile.png', fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await student.close(); student = undefined;
    restored = await launch({ env: { ...environment, SCHOOL_TEST_DATA: studentData } });
    const savedPage = await restored.firstWindow();
    await savedPage.waitForFunction(() => document.querySelector('.connection-orb-button')?.classList.contains('is-blue'));
    assert.equal((await savedPage.evaluate(() => window.desktop.connectionState())).connected, true);
    await teacher.close();
    await savedPage.waitForFunction(() => document.querySelector('.connection-orb-button')?.classList.contains('is-red'), undefined, { timeout: 20000 });
    console.log('Connection orb passed: discovery, code-only pairing, wrong-code rejection, red/green/blue states, saved pairing, loss of connection, responsive panel.');
  } finally { await student?.close(); await restored?.close(); await teacher.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
